`timescale 1ns/1ps

// Empty D0 top for Zynq/FMC preparation.
// The acquisition board must remain disconnected. This module never emits
// SCLK or DIN activity and never releases any ADS1299 control input.
module d0_empty_top (
    input  wire        pl_clk,
    input  wire        pl_reset_n,
    input  wire        adc1_dout,
    input  wire        adc2_dout,
    input  wire        adc1_drdy_n,
    input  wire        adc2_drdy_n,
    output wire        adc_din,
    output wire        adc_pwdn_n,
    output wire        adc_reset_n,
    output wire        adc_sclk,
    output wire        adc_start,
    output wire        adc1_cs_n,
    output wire        adc2_cs_n
);

    localparam [3:0] D0_SAFE_LOW = 4'd0;

    reg [3:0]  d0_state;
    reg [31:0] safe_counter;
    reg [1:0]  adc1_drdy_sync;
    reg [1:0]  adc2_drdy_sync;
    reg [1:0]  adc1_dout_sync;
    reg [1:0]  adc2_dout_sync;

    wire [6:0] control_outputs = {
        adc_din,
        adc_pwdn_n,
        adc_reset_n,
        adc_sclk,
        adc_start,
        adc1_cs_n,
        adc2_cs_n
    };
    wire [1:0] drdy_sync = {adc2_drdy_sync[1], adc1_drdy_sync[1]};
    wire [1:0] dout_sync = {adc2_dout_sync[1], adc1_dout_sync[1]};
    wire [7:0] error_flags = 8'd0;
    wire       oe_cmd = 1'b0;
    wire       static_low_ok = (control_outputs == 7'd0);

    // All ADS-facing outputs are hard low in this empty project.
    assign adc_din     = 1'b0;
    assign adc_pwdn_n  = 1'b0;
    assign adc_reset_n = 1'b0;
    assign adc_sclk    = 1'b0;
    assign adc_start   = 1'b0;
    assign adc1_cs_n   = 1'b0;
    assign adc2_cs_n   = 1'b0;

    always @(posedge pl_clk or negedge pl_reset_n) begin
        if (!pl_reset_n) begin
            d0_state       <= D0_SAFE_LOW;
            safe_counter   <= 32'd0;
            adc1_drdy_sync <= 2'b11;
            adc2_drdy_sync <= 2'b11;
            adc1_dout_sync <= 2'b00;
            adc2_dout_sync <= 2'b00;
        end else begin
            d0_state       <= D0_SAFE_LOW;
            safe_counter   <= safe_counter + 32'd1;
            adc1_drdy_sync <= {adc1_drdy_sync[0], adc1_drdy_n};
            adc2_drdy_sync <= {adc2_drdy_sync[0], adc2_drdy_n};
            adc1_dout_sync <= {adc1_dout_sync[0], adc1_dout};
            adc2_dout_sync <= {adc2_dout_sync[0], adc2_dout};
        end
    end

    // ila_d0 is generated by board/vivado/d0_empty_project.tcl.
    ila_d0 ila_i (
        .clk    (pl_clk),
        .probe0 (d0_state),
        .probe1 (safe_counter),
        .probe2 (control_outputs),
        .probe3 (drdy_sync),
        .probe4 (dout_sync),
        .probe5 (error_flags),
        .probe6 (oe_cmd),
        .probe7 (pl_reset_n),
        .probe8 (static_low_ok),
        .probe9 (8'd0)
    );

endmodule

// Log code of an unsigned value: 0 for 0, else min(255, 4*msb + two bits below the msb + 1)  (golden/health_golden.py code()).
// Loop-free: a binary-search normaliser (found the msb), then one variable shift for the two bits below it.
module eeg_health_code70(input wire [69:0] v, output wire [7:0] code);
    wire [127:0] x = {58'd0, v};
    wire b6 = |x[127:64];
    wire [63:0] x1 = b6 ? x[127:64] : x[63:0];
    wire b5 = |x1[63:32];
    wire [31:0] x2 = b5 ? x1[63:32] : x1[31:0];
    wire b4 = |x2[31:16];
    wire [15:0] x3 = b4 ? x2[31:16] : x2[15:0];
    wire b3 = |x3[15:8];
    wire [7:0] x4 = b3 ? x3[15:8] : x3[7:0];
    wire b2 = |x4[7:4];
    wire [3:0] x5 = b2 ? x4[7:4] : x4[3:0];
    wire b1 = |x5[3:2];
    wire [1:0] x6 = b1 ? x5[3:2] : x5[1:0];
    wire b0 = x6[1];
    wire [6:0] msb = {b6, b5, b4, b3, b2, b1, b0};

`timescale 1ns/1ps
// CANDIDATE (simulation verified only). Full-rate (976.5625 SPS) bipolar ECG front end + QRS feature engine.
//
//   d  = B - A                       25-bit, exact (no narrowing)
//   x  = d << 4                      4 fractional bits keep the 0.5 Hz high-pass out of the 24-bit rounding dead zone
//   y  = HP(0.5 Hz) -> notch(50 Hz, Q=30) -> LP(45 Hz)   three Q30 transposed-DF2 biquads, 72-bit state,
//        round-half-away, S32 saturation  (same filter family as the 244 Hz profile, coefficients for 976.5625 Hz)
//   dvs = sat18( (y0 + 2*y1 - 2*y3 - y4) >> 4 )            5-point derivative
//   mwi = (sum of dvs^2 over 128 samples) >> 7             moving-window integral
//   peak engine: local maximum of mwi, 1.0 s settle, 1.95 s learning window, then adaptive threshold
//        thr = npki + (spki-npki)/4, refractory 195 samples (200 ms), floor MIN_PK. Emits CANDIDATE events only
//        (sample index of the mwi maximum, peak value, threshold). The event index lags the R wave by the
//        filter + window delay (tens of ms, +-~20 ms jitter): R localisation and HR/RR decisions stay in PS.
// One 32x32 multiplier (3-stage pipeline) is shared by all 15 multiplies of a sample (~45 clocks of 102,400).
// Bit-exact contract: golden/mr_golden.py EcgFront.  Not a medical/diagnostic function.
module eeg_ecg_front_v3 #(
    // Q30 coefficients {b0,b1,b2,a1,a2}, generated by golden/mr_golden.py (ecg_coef.txt)
    parameter signed [31:0] HP_B0 = 32'sd1071302099, HP_B1 = -32'sd2142604198, HP_B2 = 32'sd1071302099,
                            HP_A1 = -32'sd2142598655, HP_A2 = 32'sd1068867918,
    parameter signed [31:0] NT_B0 = 32'sd1068113242, NT_B1 = -32'sd2026637151, NT_B2 = 32'sd1068113242,
                            NT_A1 = -32'sd2026637151, NT_A2 = 32'sd1062484660,
    parameter signed [31:0] LP_B0 = 32'sd18592065, LP_B1 = 32'sd37184129, LP_B2 = 32'sd18592065,
                            LP_A1 = -32'sd1712402597, LP_A2 = 32'sd713029032,
    parameter integer SETTLE = 977, LEARN_END = 2930, REFRACT = 195, FLAT_RUN = 977,
    parameter integer MIN_PK = 4096
)(
    input  wire clk, input wire rst_n, input wire flush,
    input  wire mode_ecg,                               // 0: idle, samples ignored
    input  wire in_valid, input wire signed [23:0] in_a, input wire signed [23:0] in_b, input wire in_clipped,
    output wire in_ready,
    output reg  out_valid,
    output reg  signed [24:0] out_diff,
    output reg  signed [31:0] out_y,
    output reg  signed [17:0] out_dvs,
    output reg  [35:0] out_mwi,
    output reg  ev_valid,                               // 1-clock pulse, candidate QRS event
    output reg  [31:0] ev_idx, output reg [35:0] ev_pk, output reg [35:0] ev_thr,
    output reg  [31:0] cnt_samples, cnt_clipped, cnt_sat, cnt_events, cnt_flat_runs, cnt_noise_peaks
);
    localparam [3:0] ST_IDLE = 0, ST_SEC = 1, ST_Q1 = 2, ST_Q2 = 3, ST_Q3 = 4, ST_Q4 = 5;
    reg [3:0] st;
    assign in_ready = (st == ST_IDLE) && mode_ecg;

    // ---- shared pipelined multiplier: operands presented in cycle t, product visible in cycle t+3
    reg signed [31:0] mop_a, mop_b;                     // combinational selection below
    reg signed [31:0] ma, mb; reg signed [63:0] mp1, mp2;
    always @(posedge clk) begin ma <= mop_a; mb <= mop_b; mp1 <= ma * mb; mp2 <= mp1; end

    reg [1:0] si;                                       // section index
    reg [3:0] t;
    reg signed [31:0] cb0, cb1, cb2, ca1, ca2;
    always @* begin
        case (si)
            2'd0: begin cb0 = HP_B0; cb1 = HP_B1; cb2 = HP_B2; ca1 = HP_A1; ca2 = HP_A2; end
            2'd1: begin cb0 = NT_B0; cb1 = NT_B1; cb2 = NT_B2; ca1 = NT_A1; ca2 = NT_A2; end
            default: begin cb0 = LP_B0; cb1 = LP_B1; cb2 = LP_B2; ca1 = LP_A1; ca2 = LP_A2; end
        endcase
    end

    reg signed [31:0] xin;                              // section input
    reg signed [31:0] yq;                               // section output (registered)
    reg signed [71:0] z1 [0:2]; reg signed [71:0] z2 [0:2]; reg signed [71:0] ef [0:2];   // ef: rounding residual (error feedback)
    reg signed [71:0] accr, p1, p3, pa1;
    reg sat_any;

    always @* begin
        mop_a = 32'sd0; mop_b = 32'sd0;
        if (st == ST_SEC) case (t)
            4'd0: begin mop_a = cb0; mop_b = xin; end
            4'd1: begin mop_a = cb1; mop_b = xin; end
            4'd2: begin mop_a = cb2; mop_b = xin; end
            4'd5: begin mop_a = ca1; mop_b = yq; end
            4'd6: begin mop_a = ca2; mop_b = yq; end
            default: ;
        endcase
    end

    // round half away from zero (>>30) and S32 saturation of accr
    wire signed [71:0] acc_abs = accr[71] ? -accr : accr;
    wire signed [71:0] r_abs = (acc_abs + 72'sd536870912) >>> 30;
    wire signed [71:0] rnd30 = accr[71] ? -r_abs : r_abs;
    wire r_over = (rnd30 > 72'sd2147483647) || (rnd30 < -72'sd2147483648);
    wire signed [31:0] r_sat = (rnd30 > 72'sd2147483647) ? 32'sh7fffffff :
                               (rnd30 < -72'sd2147483648) ? 32'sh80000000 : rnd30[31:0];

    // ---- QRS engine state
    reg signed [31:0] yh [0:4];
    reg signed [34:0] dv; reg signed [17:0] dvs_r; reg [35:0] sq_r;
    (* ram_style = "distributed" *) reg [35:0] mwi_ring [0:127];
    reg [6:0] mpos; reg [35:0] old_r; reg [41:0] wsum;
    reg [35:0] m1, m2;
    wire [35:0] mwi_c = {1'b0, wsum[41:7]};
    reg [31:0] n; reg signed [31:0] last_peak;
    reg [35:0] spki, npki, lmax;
    reg [31:0] flat; reg signed [24:0] d_r;
    reg signed [17:0] dvs_c;
    wire signed [35:0] dv_sh = (dv >= 0) ? (dv >>> 4) : -((-dv) >>> 4);   // truncate toward zero
    wire signed [31:0] pk_idx = $signed(n) - 32'sd1;
    wire is_max_q4 = (m1 > m2) && (m1 >= mwi_c);
    wire [35:0] spki_eff = (spki == 0 && lmax != 0) ? lmax : spki;
    wire signed [37:0] thr_s = $signed({2'b00, npki}) + ((($signed({2'b00, spki_eff})) - ($signed({2'b00, npki}))) >>> 2);
    wire [35:0] thr_now = thr_s[35:0];
    integer i;
    // window RAM: separate, reset-free process so that it maps to distributed RAM instead of 4.6k flip-flops
    wire [35:0] ring_rd = mwi_ring[mpos];
    always @(posedge clk) if (st == ST_Q3) mwi_ring[mpos] <= sq_r;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            st <= ST_IDLE; si <= 0; t <= 0; xin <= 0; yq <= 0; accr <= 0; p1 <= 0; p3 <= 0; pa1 <= 0; sat_any <= 0;
            for (i = 0; i < 3; i = i + 1) begin z1[i] <= 0; z2[i] <= 0; ef[i] <= 0; end
            for (i = 0; i < 5; i = i + 1) yh[i] <= 0;
            dv <= 0; dvs_r <= 0; sq_r <= 0; mpos <= 0; old_r <= 0; wsum <= 0; m1 <= 0; m2 <= 0;
            n <= 0; last_peak <= -32'sd1000000000; spki <= 0; npki <= 0; lmax <= 0; flat <= 0; d_r <= 0;
            out_valid <= 0; out_diff <= 0; out_y <= 0; out_dvs <= 0; out_mwi <= 0; ev_valid <= 0; ev_idx <= 0; ev_pk <= 0; ev_thr <= 0;
            cnt_samples <= 0; cnt_clipped <= 0; cnt_sat <= 0; cnt_events <= 0; cnt_flat_runs <= 0; cnt_noise_peaks <= 0;
        end else if (flush || !mode_ecg) begin
            st <= ST_IDLE; si <= 0; t <= 0;
            for (i = 0; i < 3; i = i + 1) begin z1[i] <= 0; z2[i] <= 0; ef[i] <= 0; end
            for (i = 0; i < 5; i = i + 1) yh[i] <= 0;
            mpos <= 0; wsum <= 0; m1 <= 0; m2 <= 0; n <= 0; last_peak <= -32'sd1000000000;
            spki <= 0; npki <= 0; lmax <= 0; flat <= 0; out_valid <= 0; ev_valid <= 0;
            cnt_samples <= 0; cnt_clipped <= 0; cnt_sat <= 0; cnt_events <= 0; cnt_flat_runs <= 0; cnt_noise_peaks <= 0;
        end else begin
            out_valid <= 1'b0; ev_valid <= 1'b0;
            case (st)
            ST_IDLE: if (in_valid && in_ready) begin
                d_r  <= ($signed({in_b[23], in_b}) - $signed({in_a[23], in_a}));
                xin  <= ($signed({{7{in_b[23]}}, in_b}) - $signed({{7{in_a[23]}}, in_a})) <<< 4;
                if (in_clipped) cnt_clipped <= cnt_clipped + 1'b1;
                si <= 0; t <= 0; sat_any <= 1'b0; st <= ST_SEC;
            end
            ST_SEC: begin
                t <= t + 1'b1;
                case (t)
                    4'd3: accr <= {{8{mp2[63]}}, mp2} + z1[si] + ef[si];          // b0*x + z1 + carried rounding residual
                    4'd4: begin                                                // y = round/sat(accr); p1 = b1*x
                        yq <= r_sat; if (r_over) sat_any <= 1'b1;
                        ef[si] <= r_over ? 72'sd0 : (accr - {{10{r_sat[31]}}, r_sat, 30'b0});
                        p1 <= {{8{mp2[63]}}, mp2};
                    end
                    4'd5: p3 <= {{8{mp2[63]}}, mp2};                           // b2*x
                    4'd8: pa1 <= {{8{mp2[63]}}, mp2};                          // a1*y
                    4'd9: begin                                                // a2*y -> state update
                        z1[si] <= p1 - pa1 + z2[si];
                        z2[si] <= p3 - {{8{mp2[63]}}, mp2};
                        if (si == 2'd2) begin
                            yh[0] <= yq; yh[1] <= yh[0]; yh[2] <= yh[1]; yh[3] <= yh[2]; yh[4] <= yh[3];
                            st <= ST_Q1;
                        end else begin xin <= yq; si <= si + 1'b1; t <= 0; end
                    end
                    default: ;
                endcase
            end
            ST_Q1: begin                                                       // derivative
                dv <= $signed(yh[0]) + (($signed(yh[1])) <<< 1) - (($signed(yh[3])) <<< 1) - $signed(yh[4]);
                old_r <= (n < 128) ? 36'd0 : ring_rd;
                st <= ST_Q2;
            end
            ST_Q2: begin                                                       // sat18, square
                dvs_c = (dv_sh > 36'sd131071) ? 18'sd131071 : (dv_sh < -36'sd131072) ? -18'sd131072 : dv_sh[17:0];
                dvs_r <= dvs_c; sq_r <= dvs_c * dvs_c;
                st <= ST_Q3;
            end
            ST_Q3: begin                                                       // moving-window sum
                mpos <= mpos + 1'b1;
                wsum <= wsum + sq_r - old_r;
                st <= ST_Q4;
            end
            ST_Q4: begin                                                       // mwi, peak logic, outputs
                                // flat-line run counter and statistics use dvs
                if (dvs_r == 0) begin
                    if (flat != 32'hffffffff) flat <= flat + 1'b1;
                    if (flat + 1 == FLAT_RUN) cnt_flat_runs <= cnt_flat_runs + 1'b1;
                end else flat <= 0;
                if (sat_any) cnt_sat <= cnt_sat + 1'b1;
                cnt_samples <= cnt_samples + 1'b1;
                if (is_max_q4) begin
                    if (pk_idx < SETTLE) ;
                    else if (pk_idx < LEARN_END) begin if (m1 > lmax) lmax <= m1; end
                    else begin
                        if (spki == 0 && lmax != 0) spki <= lmax;
                        if (($signed(pk_idx) - last_peak) >= REFRACT) begin
                            if (m1 > thr_now && m1 >= MIN_PK) begin
                                spki <= $signed({2'b00, spki_eff}) + (($signed({2'b00, m1}) - $signed({2'b00, spki_eff})) >>> 3);
                                last_peak <= pk_idx;
                                ev_valid <= 1'b1; ev_idx <= pk_idx; ev_pk <= m1; ev_thr <= thr_now;
                                cnt_events <= cnt_events + 1'b1;
                            end else begin
                                npki <= $signed({2'b00, npki}) + (($signed({2'b00, m1}) - $signed({2'b00, npki})) >>> 3);
                                cnt_noise_peaks <= cnt_noise_peaks + 1'b1;
                            end
                        end
                    end
                end
                m2 <= m1; m1 <= mwi_c;
                n <= n + 1'b1;
                out_valid <= 1'b1; out_diff <= d_r; out_y <= yh[0]; out_dvs <= dvs_r; out_mwi <= mwi_c;
                st <= ST_IDLE;
            end
            default: st <= ST_IDLE;
            endcase
        end
    end
endmodule
